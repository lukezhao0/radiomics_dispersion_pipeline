def load_feature_matrix(path: str) -> pd.DataFrame:
    if not os.path.exists(path):
        raise FileNotFoundError(f"Feature matrix not found: {path}")
    df = pd.read_csv(path)
    required = {"case_id", "dispersion_true_high_low"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(
            f"Feature matrix missing required columns: {sorted(missing)}. "
            f"Found columns: {list(df.columns)}"
        )
    return df

def load_univariate(path: Optional[str]) -> Optional[pd.DataFrame]:
    if path is None:
        return None
    if not os.path.exists(path):
        raise FileNotFoundError(f"Univariate associations file not found: {path}")
    df = pd.read_csv(path)
    if "feature" not in df.columns:
        raise ValueError("Univariate associations file must contain a 'feature' column.")
    return df


# -----------------------------
# Feature direction inference
# -----------------------------

def compute_feature_direction_from_univariate(
    feature_cols: List[str],
    uni_df: Optional[pd.DataFrame],
    feat_df: pd.DataFrame,
) -> pd.DataFrame:
    """
    Assign each feature a direction:
      +1 = high-dispersion-associated
      -1 = low-dispersion-associated

    Priority:
      1) use univariate association table if available
      2) otherwise compute directly from feat_df vs dispersion_true_high_low

    Returned columns include:
      feature, direction, association_score, support_nonzero
    """

    rows = []

    y = safe_numeric(feat_df["dispersion_true_high_low"])
    valid_y = y.isin([0, 1])

    uni_lookup = None
    if uni_df is not None:
        uni_lookup = uni_df.set_index("feature", drop=False)

    for col in feature_cols:
        x = safe_numeric(feat_df[col])
        support = nonzero_support(x)

        direction = 0
        assoc = np.nan

        if uni_lookup is not None and col in uni_lookup.index:
            r = uni_lookup.loc[col]

            candidates = []
            if "highlow_spearman_rho" in r.index and pd.notna(r["highlow_spearman_rho"]):
                candidates.append(float(r["highlow_spearman_rho"]))
            if "score_spearman_rho" in r.index and pd.notna(r["score_spearman_rho"]):
                candidates.append(float(r["score_spearman_rho"]))

            if len(candidates) > 0:
                assoc = candidates[0]
                direction = 1 if assoc > 0 else (-1 if assoc < 0 else 0)

        if direction == 0:
            mask = valid_y & x.notna()
            if int(mask.sum()) >= 3 and len(np.unique(y.loc[mask])) >= 2:
                xh = x.loc[mask & (y == 1)]
                xl = x.loc[mask & (y == 0)]
                if len(xh) > 0 and len(xl) > 0:
                    assoc = float(xh.mean() - xl.mean())
                    direction = 1 if assoc > 0 else (-1 if assoc < 0 else 0)

        rows.append({
            "feature": col,
            "support_nonzero": support,
            "association_score": assoc,
            "direction": direction,
        })

    out = pd.DataFrame(rows)
    return out


# -----------------------------
# Case ordering
# -----------------------------

def order_cases(
    feat_df: pd.DataFrame,
    case_group_order: str = "high_first",
) -> pd.DataFrame:
    """
    Order cases so axis grouping is by high vs low dispersion.

    Within each group:
    - sort by continuous dispersion_true descending
    - then by case_id
    """
    df = feat_df.copy()
    df["dispersion_true_high_low_num"] = safe_numeric(df["dispersion_true_high_low"])
    df["dispersion_true_num"] = safe_numeric(df.get("dispersion_true", np.nan))

    df = df[df["dispersion_true_high_low_num"].isin([0, 1])].copy()

    if case_group_order == "high_first":
        ascending_group = False
    elif case_group_order == "low_first":
        ascending_group = True
    else:
        raise ValueError("--case_group_order must be 'high_first' or 'low_first'")

    df = df.sort_values(
        by=["dispersion_true_high_low_num", "dispersion_true_num", "case_id"],
        ascending=[ascending_group, False, True],
        na_position="last",
    ).reset_index(drop=True)

    return df


# -----------------------------
# Feature selection and ordering
# -----------------------------

def choose_features(
    feat_df: pd.DataFrame,
    uni_df: Optional[pd.DataFrame],
    min_support: int,
    max_features_per_panel: Optional[int],
) -> pd.DataFrame:
    """
    Select as many informative features as possible while excluding:
    - metadata columns
    - all-zero features
    - zero-variance features
    - features with support < min_support

    Then assign direction and order:
    - high-dispersion-associated features first
    - low-dispersion-associated features second
    """
    feature_cols = [c for c in feat_df.columns if c not in META_COLS]

    keep = []
    for col in feature_cols:
        x = safe_numeric(feat_df[col])
        if x.notna().sum() == 0:
            continue

        x0 = x.fillna(0)
        if x0.nunique(dropna=False) <= 1:
            continue

        supp = nonzero_support(x)
        if supp < min_support:
            continue

        keep.append(col)

    direction_df = compute_feature_direction_from_univariate(
        feature_cols=keep,
        uni_df=uni_df,
        feat_df=feat_df,
    )

    high_df = direction_df[direction_df["direction"] == 1].copy()
    low_df = direction_df[direction_df["direction"] == -1].copy()
    neutral_df = direction_df[direction_df["direction"] == 0].copy()

    high_df["abs_assoc"] = high_df["association_score"].abs()
    low_df["abs_assoc"] = low_df["association_score"].abs()
    neutral_df["abs_assoc"] = neutral_df["association_score"].abs()

    high_df = high_df.sort_values(
        by=["abs_assoc", "support_nonzero", "feature"],
        ascending=[False, False, True],
        na_position="last",
    )
    low_df = low_df.sort_values(
        by=["abs_assoc", "support_nonzero", "feature"],
        ascending=[False, False, True],
        na_position="last",
    )
    neutral_df = neutral_df.sort_values(
        by=["support_nonzero", "feature"],
        ascending=[False, True],
        na_position="last",
    )

    reassigned_high = []
    reassigned_low = []
    for _, r in neutral_df.iterrows():
        assoc = r["association_score"]
        if pd.notna(assoc) and assoc > 0:
            reassigned_high.append(r)
        elif pd.notna(assoc) and assoc < 0:
            reassigned_low.append(r)
        else:
            if len(high_df) <= len(low_df):
                reassigned_high.append(r)
            else:
                reassigned_low.append(r)

    if len(reassigned_high) > 0:
        high_df = pd.concat([high_df, pd.DataFrame(reassigned_high)], ignore_index=True)
    if len(reassigned_low) > 0:
        low_df = pd.concat([low_df, pd.DataFrame(reassigned_low)], ignore_index=True)

    full_df = pd.concat([high_df, low_df], ignore_index=True)

    if max_features_per_panel is not None:
        full_df = full_df.iloc[:max_features_per_panel].copy()

    full_df["feature_group"] = np.where(full_df["direction"].fillna(0) >= 0, "high_associated", "low_associated")

    return full_df.reset_index(drop=True)


# -----------------------------
# Matrix scaling for visualization
# -----------------------------

def robust_scale_feature_for_display(
    series: pd.Series,
    feature_value_mode: str = "auto",
) -> pd.Series:
    """
    Convert one feature to [0, 1] for display.

    Modes:
    - auto:
        binary stays binary
        otherwise robust percentile scaling
    - binary_raw:
        only appropriate when all selected features are binary
    - robust:
        robust scaling for all features
    """
    s = safe_numeric(series)

    if feature_value_mode not in {"auto", "binary_raw", "robust"}:
        raise ValueError("--feature_value_mode must be one of: auto, binary_raw, robust")

    if feature_value_mode == "binary_raw":
        return s

    if feature_value_mode == "auto" and is_binary_series(s):
        return s

    nonmissing = s.dropna()
    if len(nonmissing) == 0:
        return s

    lo = float(np.nanpercentile(nonmissing, 5))
    hi = float(np.nanpercentile(nonmissing, 95))

    if math.isclose(lo, hi):
        lo = float(np.nanmin(nonmissing))
        hi = float(np.nanmax(nonmissing))

    if math.isclose(lo, hi):
        return pd.Series(np.where(s.notna(), 0.0, np.nan), index=s.index)

    scaled = (s - lo) / (hi - lo)
    scaled = scaled.clip(lower=0.0, upper=1.0)
    return scaled


def build_display_matrix(
    feat_df_ordered_cases: pd.DataFrame,
    feature_order_df: pd.DataFrame,
    feature_value_mode: str,
) -> Tuple[pd.DataFrame, List[str], List[str]]:
    feature_names = feature_order_df["feature"].tolist()
    display_df = feat_df_ordered_cases[feature_names].copy()

    for col in feature_names:
        display_df[col] = robust_scale_feature_for_display(display_df[col], feature_value_mode=feature_value_mode)

    mat = display_df.T
    mat.index = [shorten_feature_name(x) for x in mat.index]

    case_labels = feat_df_ordered_cases["case_id"].astype(str).tolist()
    feature_labels = mat.index.tolist()

    return mat, case_labels, feature_labels


