#!/usr/bin/env python3
"""
Plot quadrant-style heatmaps for case-by-feature lexical dispersion matrices.

Goal
----
For each modality-specific case_feature_matrix_<mode>.csv generated by
feature_discovery_eval.py, produce a heatmap where:

Default orientation:
- x-axis = patient cases
    grouped into TRUE high-dispersion cases and TRUE low-dispersion cases
- y-axis = features
    grouped into high-dispersion-associated features (top)
    and low-dispersion-associated features (bottom)

Optional swapped orientation:
- x-axis = features
- y-axis = patient cases

The intended visual pattern is a 4-quadrant structure:
- high-dispersion cases enriched for high-dispersion features
- low-dispersion cases enriched for low-dispersion features

This script is written to be robust for the output format of the provided
feature_discovery_eval.py code.

Inputs
------
For each modality (MRI or pathology), the script expects:
1) case_feature_matrix_<mode>.csv
2) optionally: univariate_feature_associations_<mode>.csv

If the univariate file is present, feature direction is taken from it.
If it is absent, direction is computed directly from the feature matrix.

Outputs
-------
For each modality, writes:
- heatmap_<mode>.png
- heatmap_<mode>.pdf
- heatmap_<mode>__feature_order.csv
- heatmap_<mode>__case_order.csv

Usage examples
--------------
python plot_dispersion_heatmaps.py \
  --mri_feature_matrix /path/to/case_feature_matrix_mri.csv \
  --mri_univariate /path/to/univariate_feature_associations_mri.csv \
  --path_feature_matrix /path/to/case_feature_matrix_path.csv \
  --path_univariate /path/to/univariate_feature_associations_path.csv \
  --out_dir /path/to/heatmap_outputs

Swap axes:
python plot_dispersion_heatmaps.py \
  --mri_feature_matrix /path/to/case_feature_matrix_mri.csv \
  --mri_univariate /path/to/univariate_feature_associations_mri.csv \
  --path_feature_matrix /path/to/case_feature_matrix_path.csv \
  --path_univariate /path/to/univariate_feature_associations_path.csv \
  --out_dir /path/to/heatmap_outputs \
  --axes_orientation features_x_cases_y

Optional tuning:
  --min_support 2
  --max_features_per_panel 250
  --case_group_order high_first
  --feature_value_mode auto

python plot_case_feature_heatmap.py \
  --mri_feature_matrix /Users/lukezhao/projects/onc/securegpt_dispersion_feature_discovery_mri/case_feature_matrix_mri.csv \
  --mri_univariate /Users/lukezhao/projects/onc/securegpt_dispersion_feature_discovery_mri/univariate_feature_associations_mri.csv \
  --path_feature_matrix /Users/lukezhao/projects/onc/securegpt_dispersion_feature_discovery_path/case_feature_matrix_path.csv \
  --path_univariate /Users/lukezhao/projects/onc/securegpt_dispersion_feature_discovery_path/univariate_feature_associations_path.csv \
  --out_dir /Users/lukezhao/projects/onc/securegpt_dispersion_heatmaps4 \
  --show_case_ticks \
  --axes_orientation features_x_cases_y


Notes
-----
- "Support" here is the number of cases with a nonzero value for the feature.
- Binary features are shown as 0/1.
- Non-binary features are scaled per feature to [0, 1] using robust percentiles
  so that mixed feature types can be visualized together.
- Missing values are shown in light gray.
"""

