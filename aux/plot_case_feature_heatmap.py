def make_heatmap_cmap():
    """
    White-to-red map with missing values in light gray.
    """
    cmap = LinearSegmentedColormap.from_list(
        "white_red",
        ["#ffffff", "#fee8c8", "#fdbb84", "#e34a33", "#b30000"]
    )
    cmap.set_bad(color="#d9d9d9")
    return cmap

def compute_figsize(n_primary: int, n_secondary: int) -> Tuple[float, float]:
    width = max(14, min(30, 8 + n_primary * 0.12))
    height = max(10, min(36, 6 + n_secondary * 0.18))
    return width, height

def plot_single_modality_heatmap(
    feat_df: pd.DataFrame,
    uni_df: Optional[pd.DataFrame],
    modality_name: str,
    out_dir: str,
    min_support: int,
    max_features_per_panel: Optional[int],
    case_group_order: str,
    feature_value_mode: str,
    show_case_ticks: bool,
    axes_orientation: str,
) -> None:
    """
    Main plotting function for one modality.
    """
    ensure_dir(out_dir)

    feat_df = feat_df.copy()

    ordered_cases_df = order_cases(feat_df, case_group_order=case_group_order)
    if len(ordered_cases_df) == 0:
        raise ValueError(f"No valid cases with dispersion_true_high_low in modality: {modality_name}")

    feature_order_df = choose_features(
        feat_df=ordered_cases_df,
        uni_df=uni_df,
        min_support=min_support,
        max_features_per_panel=max_features_per_panel,
    )
    if len(feature_order_df) == 0:
        raise ValueError(f"No eligible features remained after filtering for modality: {modality_name}")

    mat, case_labels, feature_labels = build_display_matrix(
        feat_df_ordered_cases=ordered_cases_df,
        feature_order_df=feature_order_df,
        feature_value_mode=feature_value_mode,
    )

    if axes_orientation == "cases_x_features_y":
        plot_df = mat
        x_labels = case_labels
        y_labels = feature_labels
        x_entity = "cases"
        y_entity = "features"
        x_group_values = safe_numeric(ordered_cases_df["dispersion_true_high_low"]).astype(int).tolist()
        y_group_values = feature_order_df["feature_group"].tolist()
    elif axes_orientation == "features_x_cases_y":
        plot_df = mat.T
        x_labels = feature_labels
        y_labels = case_labels
        x_entity = "features"
        y_entity = "cases"
        x_group_values = feature_order_df["feature_group"].tolist()
        y_group_values = safe_numeric(ordered_cases_df["dispersion_true_high_low"]).astype(int).tolist()
    else:
        raise ValueError("--axes_orientation must be 'cases_x_features_y' or 'features_x_cases_y'")

    arr = plot_df.values.astype(float)
    arr_masked = np.ma.masked_invalid(arr)

    n_rows, n_cols = arr.shape
    fig_w, fig_h = compute_figsize(n_primary=n_cols, n_secondary=n_rows)

    cmap = make_heatmap_cmap()

    fig, ax = plt.subplots(figsize=(fig_w, fig_h))
    im = ax.imshow(
        arr_masked,
        aspect="auto",
        interpolation="nearest",
        cmap=cmap,
        vmin=0,
        vmax=1,
    )

    ax.set_xlabel("Cases" if x_entity == "cases" else "Features")
    ax.set_ylabel("Features" if y_entity == "features" else "Cases")

    n_high_cases = int((safe_numeric(ordered_cases_df["dispersion_true_high_low"]) == 1).sum())
    n_low_cases = int((safe_numeric(ordered_cases_df["dispersion_true_high_low"]) == 0).sum())
    n_high_features = int((feature_order_df["feature_group"] == "high_associated").sum())
    n_low_features = int((feature_order_df["feature_group"] == "low_associated").sum())

    ax.set_title(
        f"{modality_name.upper()} lexical dispersion heatmap\n"
        f"Cases: high={n_high_cases}, low={n_low_cases} | "
        f"Features: high-associated={n_high_features}, low-associated={n_low_features}",
        fontsize=14,
        pad=14,
    )

    # Y ticks
    if y_entity == "features":
        if len(y_labels) <= 140:
            ytick_positions = np.arange(len(y_labels))
            ytick_labels = y_labels
        else:
            step = max(1, int(np.ceil(len(y_labels) / 140)))
            ytick_positions = np.arange(0, len(y_labels), step)
            ytick_labels = [y_labels[i] for i in ytick_positions]
        ax.set_yticks(ytick_positions)
        ax.set_yticklabels(ytick_labels, fontsize=8)
    else:
        if show_case_ticks and len(y_labels) <= 140:
            ytick_positions = np.arange(len(y_labels))
            ytick_labels = y_labels
            ax.set_yticks(ytick_positions)
            ax.set_yticklabels(ytick_labels, fontsize=6)
        else:
            ax.set_yticks([])

    # X ticks
    if x_entity == "cases":
        if show_case_ticks and len(x_labels) <= 140:
            xtick_positions = np.arange(len(x_labels))
            xtick_labels = x_labels
            ax.set_xticks(xtick_positions)
            ax.set_xticklabels(xtick_labels, rotation=90, fontsize=6)
        else:
            ax.set_xticks([])
    else:
        if len(x_labels) <= 140:
            xtick_positions = np.arange(len(x_labels))
            xtick_labels = x_labels
        else:
            step = max(1, int(np.ceil(len(x_labels) / 140)))
            xtick_positions = np.arange(0, len(x_labels), step)
            xtick_labels = [x_labels[i] for i in xtick_positions]
        ax.set_xticks(xtick_positions)
        ax.set_xticklabels(xtick_labels, rotation=90, fontsize=8)

    # Group separators
    if x_entity == "cases":
        change_points_x = []
        for i in range(1, len(x_group_values)):
            if x_group_values[i] != x_group_values[i - 1]:
                change_points_x.append(i)
    else:
        change_points_x = []
        for i in range(1, len(x_group_values)):
            if x_group_values[i] != x_group_values[i - 1]:
                change_points_x.append(i)

    if y_entity == "features":
        change_points_y = []
        for i in range(1, len(y_group_values)):
            if y_group_values[i] != y_group_values[i - 1]:
                change_points_y.append(i)
    else:
        change_points_y = []
        for i in range(1, len(y_group_values)):
            if y_group_values[i] != y_group_values[i - 1]:
                change_points_y.append(i)

    for cp in change_points_x:
        ax.axvline(cp - 0.5, color="black", linewidth=2.0)

    for cp in change_points_y:
        ax.axhline(cp - 0.5, color="black", linewidth=2.0)

    # Quadrant/group labels
    if len(change_points_x) == 1 and len(change_points_y) == 1:
        v = change_points_x[0]
        h = change_points_y[0]

        if x_entity == "cases":
            left_label = "High-dispersion cases" if case_group_order == "high_first" else "Low-dispersion cases"
            right_label = "Low-dispersion cases" if case_group_order == "high_first" else "High-dispersion cases"
        else:
            left_label = "High-dispersion-associated features"
            right_label = "Low-dispersion-associated features"

        if y_entity == "features":
            top_label = "High-dispersion-associated features"
            bottom_label = "Low-dispersion-associated features"
        else:
            top_label = "High-dispersion cases" if case_group_order == "high_first" else "Low-dispersion cases"
            bottom_label = "Low-dispersion cases" if case_group_order == "high_first" else "High-dispersion cases"

        ax.text(v / 2, -2.5, left_label, ha="center", va="bottom", fontsize=10)
        ax.text((v + arr.shape[1]) / 2, -2.5, right_label, ha="center", va="bottom", fontsize=10)
        ax.text(-1.2, h / 2, top_label, ha="right", va="center", rotation=90, fontsize=10)
        ax.text(-1.2, (h + arr.shape[0]) / 2, bottom_label, ha="right", va="center", rotation=90, fontsize=10)

    cbar = fig.colorbar(im, ax=ax, fraction=0.025, pad=0.02)
    cbar.set_label("Feature value (binary raw or robustly scaled 0–1)", rotation=90)

    for spine in ax.spines.values():
        spine.set_visible(False)

    plt.tight_layout()

    suffix = "cases_x_features_y" if axes_orientation == "cases_x_features_y" else "features_x_cases_y"
    out_png = os.path.join(out_dir, f"heatmap_{modality_name}__{suffix}.png")
    out_pdf = os.path.join(out_dir, f"heatmap_{modality_name}__{suffix}.pdf")
    out_case_csv = os.path.join(out_dir, f"heatmap_{modality_name}__case_order.csv")
    out_feature_csv = os.path.join(out_dir, f"heatmap_{modality_name}__feature_order.csv")

    fig.savefig(out_png, dpi=300, bbox_inches="tight")
    fig.savefig(out_pdf, bbox_inches="tight")
    plt.close(fig)

    case_out = ordered_cases_df[[
        "case_id",
        "row_index",
        "report_mode",
        "dispersion_true",
        "dispersion_true_high_low",
        "relapse_true",
    ]].copy()
    case_out["plot_case_index"] = np.arange(len(case_out))
    case_out.to_csv(out_case_csv, index=False)

    feature_out = feature_order_df.copy()
    feature_out["plot_feature_index"] = np.arange(len(feature_out))
    feature_out["display_label"] = feature_out["feature"].map(shorten_feature_name)
    feature_out.to_csv(out_feature_csv, index=False)

    print(f"[SAVE] {modality_name}: {out_png}")
    print(f"[SAVE] {modality_name}: {out_pdf}")
    print(f"[SAVE] {modality_name}: {out_case_csv}")
    print(f"[SAVE] {modality_name}: {out_feature_csv}")


