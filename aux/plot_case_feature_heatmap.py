def infer_modality_name(feature_matrix_path: str, explicit_name: Optional[str] = None) -> str:
    if explicit_name:
        return explicit_name
    base = os.path.basename(feature_matrix_path).lower()
    if "mri" in base:
        return "mri"
    if "path" in base:
        return "path"
    return "modality"

def parse_args():
    parser = argparse.ArgumentParser()

    parser.add_argument("--mri_feature_matrix", type=str, default=None,
                        help="Path to case_feature_matrix_mri.csv")
    parser.add_argument("--mri_univariate", type=str, default=None,
                        help="Path to univariate_feature_associations_mri.csv")

    parser.add_argument("--path_feature_matrix", type=str, default=None,
                        help="Path to case_feature_matrix_path.csv")
    parser.add_argument("--path_univariate", type=str, default=None,
                        help="Path to univariate_feature_associations_path.csv")

    parser.add_argument("--out_dir", type=str, required=True,
                        help="Directory to write heatmap outputs")

    parser.add_argument("--min_support", type=int, default=DEFAULT_MIN_SUPPORT,
                        help="Minimum number of nonzero cases required for a feature to be included")

    parser.add_argument("--max_features_per_panel", type=int, default=DEFAULT_MAX_FEATURES_PER_PANEL,
                        help="Optional cap on number of features per modality heatmap; default uses all eligible features")

    parser.add_argument("--case_group_order", type=str, default="high_first",
                        choices=["high_first", "low_first"],
                        help="Whether high-dispersion cases appear first or low-dispersion cases appear first")

    parser.add_argument("--feature_value_mode", type=str, default="auto",
                        choices=["auto", "binary_raw", "robust"],
                        help=(
                            "How to scale features for display. "
                            "'auto' keeps binary features raw and robust-scales non-binary features; "
                            "'binary_raw' shows raw values (best if all plotted features are binary); "
                            "'robust' robust-scales all features."
                        ))

    parser.add_argument("--show_case_ticks", action="store_true",
                        help="Show case_id tick labels on the case axis when feasible")

    parser.add_argument("--axes_orientation", type=str, default="cases_x_features_y",
                        choices=["cases_x_features_y", "features_x_cases_y"],
                        help=(
                            "Set plot orientation. "
                            "'cases_x_features_y' = cases on x-axis, features on y-axis. "
                            "'features_x_cases_y' = features on x-axis, cases on y-axis."
                        ))

    return parser.parse_args()


def main():
    args = parse_args()
    ensure_dir(args.out_dir)

    if args.mri_feature_matrix is None and args.path_feature_matrix is None:
        raise ValueError("At least one of --mri_feature_matrix or --path_feature_matrix must be provided.")

    if args.mri_feature_matrix is not None:
        print("[LOAD] MRI feature matrix")
        mri_feat = load_feature_matrix(args.mri_feature_matrix)
        mri_uni = load_univariate(args.mri_univariate)
        plot_single_modality_heatmap(
            feat_df=mri_feat,
            uni_df=mri_uni,
            modality_name=infer_modality_name(args.mri_feature_matrix, explicit_name="mri"),
            out_dir=args.out_dir,
            min_support=args.min_support,
            max_features_per_panel=args.max_features_per_panel,
            case_group_order=args.case_group_order,
            feature_value_mode=args.feature_value_mode,
            show_case_ticks=args.show_case_ticks,
            axes_orientation=args.axes_orientation,
        )

    if args.path_feature_matrix is not None:
        print("[LOAD] Pathology feature matrix")
        path_feat = load_feature_matrix(args.path_feature_matrix)
        path_uni = load_univariate(args.path_univariate)
        plot_single_modality_heatmap(
            feat_df=path_feat,
            uni_df=path_uni,
            modality_name=infer_modality_name(args.path_feature_matrix, explicit_name="path"),
            out_dir=args.out_dir,
            min_support=args.min_support,
            max_features_per_panel=args.max_features_per_panel,
            case_group_order=args.case_group_order,
            feature_value_mode=args.feature_value_mode,
            show_case_ticks=args.show_case_ticks,
            axes_orientation=args.axes_orientation,
        )

    print("[DONE] Heatmap generation complete.")


if __name__ == "__main__":
    main()